using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using PdfObjectKit.Models;
using PdfObjectKit.Options;
using PdfObjectKit.Parsers;
using PdfObjectKit.Readers;
using PdfObjectKit.Writers;
using static PdfObjectKit.Primitives.PdfPrimitives;

namespace PdfObjectKit.Editors;

/// <summary>Rebuilds a PDF with lossless stream compression and conservative resource sharing.</summary>
public static class PdfDocumentCompressor
{
    private static readonly string[] StorageKeys = ["Size", "Prev", "XRefStm", "Type", "W", "Index", "Length", "Filter", "DecodeParms"];

    public static PdfCompressionResult Compress(byte[] source, PdfCompressionOptions? options = null, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(source);
        options ??= new();
        if (options.MaxDecodedBytes <= 0)
        {
            throw new ArgumentOutOfRangeException(nameof(options.MaxDecodedBytes));
        }
        cancellationToken.ThrowIfCancellationRequested();
        var document = PdfReader.Read(source);
        if (document.Security is not null)
        {
            throw new NotSupportedException("Unlock this PDF before compression. Protect the result again when downloading if needed.");
        }
        // A full rewrite cannot preserve byte-range signatures, including document timestamps.
        if (document.Objects.SelectMany(item => Walk(item.Value)).Any(value => value.Entries?.ContainsKey("ByteRange") == true))
        {
            throw new NotSupportedException("Compression would invalidate existing digital signatures.");
        }
        foreach (var key in StorageKeys)
        {
            document.Trailer.Entries!.Remove(key);
        }
        // Stream lengths are regenerated by the writer; old indirect length objects need not stay live.
        foreach (var stream in document.Objects.Where(item => item.Value.Type == "stream"))
        {
            stream.Value.Entries!.Remove("Length");
        }
        var removed = options.RemoveUnusedObjects ? Prune(document, cancellationToken) : 0;
        var compressed = 0;
        long decodedBytes = 0;
        var notes = new HashSet<string>();
        if (options.CompressStreams)
        {
            foreach (var item in document.Objects.Where(item => item.Value.Type == "stream"))
            {
                cancellationToken.ThrowIfCancellationRequested();
                var stream = item.Value;
                var entries = stream.Entries!;
                // External streams and metadata have compatibility requirements; retain their encoding.
                if (entries.ContainsKey("F") || entries.GetValueOrDefault("Type")?.Name is "Metadata" or "XRef" or "ObjStm")
                {
                    continue;
                }
                if (new[] { "Filter", "DecodeParms" }.Any(key => entries.TryGetValue(key, out var value) && Walk(value).Any(child => child.Type == "reference")))
                {
                    notes.Add("Streams with indirect filter settings were preserved in their original encoding.");
                    continue;
                }
                if (decodedBytes >= options.MaxDecodedBytes)
                {
                    notes.Add("The decoded-data budget was reached; remaining streams were preserved.");
                    break;
                }
                byte[] decoded;
                try
                {
                    decoded = PdfStreamDecoder.Decode(stream);
                }
                catch (NotSupportedException)
                {
                    // JPEG, JPEG2000, JBIG2 and other specialized encodings stay byte-for-byte intact.
                    continue;
                }
                catch (Exception ex) when (ex is InvalidDataException or FormatException or OverflowException)
                {
                    notes.Add("Some streams could not be decoded and were preserved in their original encoding.");
                    continue;
                }
                decodedBytes += decoded.LongLength;
                if (decodedBytes > options.MaxDecodedBytes)
                {
                    notes.Add("The decoded-data budget was reached; remaining streams were preserved.");
                    break;
                }
                using var buffer = new MemoryStream();
                using (var deflater = new ZLibStream(buffer, CompressionLevel.SmallestSize, leaveOpen: true))
                {
                    deflater.Write(decoded);
                }
                var encoded = buffer.ToArray();
                // Allow for the new filter dictionary overhead; never expand a stream for a marginal saving.
                if (encoded.Length + 32 >= Convert.FromBase64String(stream.Base64!).Length)
                {
                    continue;
                }
                stream.Base64 = Convert.ToBase64String(encoded);
                entries["Filter"] = Name("FlateDecode");
                entries.Remove("DecodeParms");
                entries.Remove("Length");
                compressed++;
            }
        }
        var duplicates = options.DeduplicateResources ? Deduplicate(document, cancellationToken) : 0;
        if (options.RemoveUnusedObjects)
        {
            removed += Prune(document, cancellationToken);
        }
        cancellationToken.ThrowIfCancellationRequested();
        if (compressed > 0 && document.PdfVersion is "1.0" or "1.1")
        {
            document.PdfVersion = "1.2";
        }
        var bytes = PdfWriter.WriteObjects(document, compactXref: true);
        var usedOriginal = options.KeepOriginalIfLarger && bytes.Length >= source.Length;
        if (usedOriginal)
        {
            notes.Add("The PDF is already compact. The original file was retained because rewriting did not reduce its size.");
        }
        return new(usedOriginal ? source.ToArray() : bytes, source.Length, bytes.Length, removed, compressed, duplicates, usedOriginal, notes.ToArray());
    }

    private static IEnumerable<PdfValue> Walk(PdfValue root)
    {
        var pending = new Stack<PdfValue>();
        pending.Push(root);
        while (pending.TryPop(out var value))
        {
            yield return value;
            foreach (var child in value.Items ?? [])
            {
                pending.Push(child);
            }
            foreach (var child in value.Entries?.Values ?? Enumerable.Empty<PdfValue>())
            {
                pending.Push(child);
            }
        }
    }

    internal static int Prune(PdfObjectDocument document, CancellationToken cancellationToken)
    {
        var objects = document.Objects.ToDictionary(item => item.Id);
        var live = new HashSet<PdfReference>();
        var pending = new Stack<PdfValue>();
        pending.Push(document.Trailer);
        while (pending.TryPop(out var root))
        {
            cancellationToken.ThrowIfCancellationRequested();
            foreach (var value in Walk(root))
            {
                if (value.Reference is { } id && live.Add(id))
                {
                    pending.Push(objects[id].Value);
                }
            }
        }
        return document.Objects.RemoveAll(item => !live.Contains(item.Id));
    }

    private static int Deduplicate(PdfObjectDocument document, CancellationToken cancellationToken)
    {
        var fonts = document.Objects.SelectMany(item => Walk(item.Value))
            .Where(value => value.Entries is not null)
            .SelectMany(value => value.Entries!.Where(pair => pair.Key is "FontFile" or "FontFile2" or "FontFile3"))
            .Select(pair => pair.Value.Reference).Where(id => id is not null).ToHashSet();
        var seen = new Dictionary<string, PdfReference>();
        var replacements = new Dictionary<PdfReference, PdfReference>();
        foreach (var item in document.Objects)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var value = item.Value;
            if (value.Type != "stream" || (value.Entries!.GetValueOrDefault("Subtype")?.Name != "Image" && !fonts.Contains(item.Id)))
            {
                continue;
            }
            // Never coalesce identity-bearing tagged images or resources with external dependencies/masks.
            if (value.Entries!.ContainsKey("StructParent") || value.Entries.ContainsKey("StructParents") || value.Entries.ContainsKey("F")
                || value.Entries.Where(pair => pair.Key != "Length").Any(pair => Walk(pair.Value).Any(child => child.Type == "reference")))
            {
                continue;
            }
            var canonical = Canonical(value);
            var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(canonical)));
            if (seen.TryGetValue(hash, out var existing))
            {
                replacements[item.Id] = existing;
            }
            else
            {
                seen[hash] = item.Id;
            }
        }
        foreach (var value in document.Objects.SelectMany(item => Walk(item.Value)).Concat(Walk(document.Trailer)))
        {
            if (value.Reference is { } id && replacements.TryGetValue(id, out var replacement))
            {
                value.Reference = replacement;
            }
        }
        document.Objects.RemoveAll(item => replacements.ContainsKey(item.Id));
        return replacements.Count;
    }

    private static string Canonical(PdfValue value)
    {
        // Length is derived by the writer; dictionary insertion order has no semantic meaning.
        if (value.Entries is not null)
        {
            return value.Type + ":" + value.Base64 + "{" + string.Join(",", value.Entries
                .Where(pair => value.Type != "stream" || pair.Key != "Length")
                .OrderBy(pair => pair.Key, StringComparer.Ordinal)
                .Select(pair => JsonSerializer.Serialize(pair.Key) + ":" + Canonical(pair.Value))) + "}";
        }
        if (value.Items is not null)
        {
            return "[" + string.Join(",", value.Items.Select(Canonical)) + "]";
        }
        return JsonSerializer.Serialize(value);
    }
}
